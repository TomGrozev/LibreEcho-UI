#!/usr/bin/env python3
"""Generate per-step microWakeWord probabilities for the engine host test.

Runs pymicro-wakeword 2.5.0 (and pymicro-features 2.0.2) over the LibreEcho
Alexa e2e fixtures and one real "Okay Nabu" clip, recording every inference
step.  The output is committed and read by tests/test_wake_engine_mww.cpp, so
the C++ test needs neither Python nor the packages.

Usage:
  python3 tests/gen_wake_engine_mww_expected.py \
      --models work/inputs/public-deps/micro-wake-word-models-source/models/v2 \
      --fixtures tests/voice-e2e/fixtures \
      --okay-nabu tests/fixtures/okay_nabu_turn_on_the_lights.wav \
      --output tests/fixtures/wake_engine_mww_expected.txt
"""

import argparse
import wave

from pymicro_wakeword import MicroWakeWord, MicroWakeWordFeatures

CLIPS = ("alexa-what-time", "alexa-twice")
OKAY_NABU = "okay-nabu"
MODELS = ("alexa", "okay_nabu")
CHUNK_BYTES = 320  # 160 samples, 10 ms at 16 kHz


def read_wav(path):
    with wave.open(path, "rb") as wav:
        assert wav.getnchannels() == 1
        assert wav.getsampwidth() == 2
        assert wav.getframerate() == 16000
        return wav.readframes(wav.getnframes())


def score_clip(model_path, audio):
    model = MicroWakeWord.from_config(model_path)
    features = MicroWakeWordFeatures()
    probabilities = []
    feature_rows = 0

    for offset in range(0, len(audio), CHUNK_BYTES):
        chunk = audio[offset:offset + CHUNK_BYTES]
        for feature in features.process_streaming(chunk):
            feature_rows += 1
            probability = model.process_streaming_prob(feature)
            if feature_rows % model.stride == 0:
                probabilities.append(probability)
    return probabilities, feature_rows


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--models", required=True)
    parser.add_argument("--fixtures", required=True)
    parser.add_argument("--okay-nabu", required=True)
    parser.add_argument("--output", required=True)
    args = parser.parse_args()

    clips = {name: f"{args.fixtures}/{name}.wav" for name in CLIPS}
    clips[OKAY_NABU] = args.okay_nabu
    lines = [
        "# Generated by tests/gen_wake_engine_mww_expected.py with"
        " pymicro-wakeword 2.5.0.",
        "# model clip step probability",
    ]
    for model in MODELS:
        model_path = f"{args.models}/{model}.json"
        for clip, path in clips.items():
            probabilities, feature_rows = score_clip(
                model_path, read_wav(path))
            for step, probability in enumerate(probabilities):
                lines.append(
                    f"{model} {clip} {step} {probability:.9f}")
            print(f"INFO {model} {clip} steps={len(probabilities)}"
                  f" feature_rows={feature_rows}")
    with open(args.output, "w", encoding="utf-8") as output:
        output.write("\n".join(lines) + "\n")
    print(f"PASS wrote {args.output}")


if __name__ == "__main__":
    main()
